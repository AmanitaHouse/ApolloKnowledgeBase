def main(argv):
    try:
        if "--check" in argv:
            errors = check_tree()
            for item in errors:
                print(f"FAIL {item}")
            if errors:
                print(f"{len(errors)} package problems")
                return 1
            info = summary()
            print(
                f"PACKAGE files={info['files']} bytes={info['bytes']} "
                f"duplicated_bytes={info['duplicated_bytes']}"
            )
            print("PACKAGE akb/ matches canonical sources: PASS")
            return 0
        info = write_tree()
        print(
            f"Wrote akb/: files={info['files']} bytes={info['bytes']} "
            f"duplicated_bytes={info['duplicated_bytes']}"
        )
        for name in sorted(info["groups"]):
            print(f"PACKAGE group {name} bytes={info['groups'][name]}")
        return 0
    except PackageError as exc:
        print(f"FAIL {exc}", file=sys.stderr)
        return 1


