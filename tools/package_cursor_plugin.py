def _powershell_convert(powershell):
    body = _convert_fn() + (
        "$rows = @(\n"
        "  'D:\\Development\\per\\ApolloKnowledgeBase|/mnt/d/Development/per/ApolloKnowledgeBase',\n"
        "  'D:/Development/per/ApolloKnowledgeBase|/mnt/d/Development/per/ApolloKnowledgeBase',\n"
        "  '/mnt/d/already|/mnt/d/already',\n"
        "  '--setup|--setup',\n"
        "  'os-friendly|os-friendly'\n"
        ")\n"
        "foreach ($row in $rows) {\n"
        "  $bits = $row.Split('|', 2)\n"
        "  $got = Convert-AkbPath $bits[0]\n"
        "  if ($got -ne $bits[1]) {\n"
        "    Write-Output \"PROBLEM=path $($bits[0]) became $got\"\n"
        "    exit 1\n"
        "  }\n"
        "}\n"
        "Write-Output 'CONVERT=ok'\n"
    )
    result = _run_powershell(powershell, body)
    if result.returncode != 0 or "CONVERT=ok" not in result.stdout:
        return [f"PowerShell path translation failed:\n{result.stdout}"]
    return []


def _powershell_resolve(powershell, win_install, win_project, install):
    body = _convert_fn() + (
        f"$install = Convert-AkbPath {_ps_quote(win_install)}\n"
        f"$project = Convert-AkbPath {_ps_quote(win_project)}\n"
        "Write-Output \"TRANSLATED=$install\"\n"
        "$output = & wsl.exe -e python3 \"$install/tools/resolve_kb.py\" \"$project\"\n"
        "Write-Output $output\n"
        "exit $LASTEXITCODE\n"
    )
    result = _run_powershell(powershell, body)
    root = _value(result.stdout, "KB_ROOT")
    translated = _value(result.stdout, "TRANSLATED")
    if (
        result.returncode != 0
        or _value(result.stdout, "KB_SOURCE") != "plugin"
        or not root
        or not translated
        or os.path.normcase(root) != os.path.normcase(translated)
        or "re-executing under WSL" in result.stdout
    ):
        return [f"PowerShell resolve of the installed package failed:\n{result.stdout}"]
    if _same(root, ROOT):
        return ["PowerShell resolve returned the repository checkout"]
    if not _same(_to_wsl(win_install), install):
        return ["PowerShell install path does not match the disposable copy"]
    return []


