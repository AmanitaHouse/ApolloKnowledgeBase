class PackageError(Exception):
    pass


def package_root():
    return os.path.join(ROOT, PACKAGE)


def _rel(path):
    return path.replace("\\", "/")


def _read(path, label):
    if os.path.islink(path):
        raise PackageError(f"refusing to package a symlink: {label}")
    if not os.path.isfile(path):
        raise PackageError(f"canonical file missing: {label}")
    with open(path, "rb") as fh:
        return fh.read()


def _walk_files(rel_dir):
    root = os.path.join(ROOT, rel_dir)
    if os.path.islink(root):
        raise PackageError(f"refusing to package a symlink: {rel_dir}")
    if not os.path.isdir(root):
        raise PackageError(f"canonical directory missing: {rel_dir}")
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(name for name in dirnames if name not in SKIP_WALK)
        for name in dirnames:
            full = os.path.join(dirpath, name)
            if os.path.islink(full):
                raise PackageError(f"refusing to package a symlink: {full}")
        for name in sorted(filenames):
            if name in SKIP_WALK or name.endswith(".pyc"):
                continue
            full = os.path.join(dirpath, name)
            rel = _rel(os.path.relpath(full, ROOT))
            found.append((rel, _read(full, rel)))
    return found


def expected_files():
    """Return {package-relative path: bytes} for a fresh akb/ tree."""
    files = {}
    for rel_dir in CONTENT_DIRS:
        for rel, data in _walk_files(rel_dir):
            files[rel] = data
    for rel in CONTENT_FILES:
        files[_rel(rel)] = _read(os.path.join(ROOT, rel), rel)
    for name in TOOL_FILES:
        rel = "tools/" + name
        files[rel] = _read(os.path.join(ROOT, "tools", name), rel)
    manifest = ".cursor-plugin/plugin.json"
    files[manifest] = _read(os.path.join(ROOT, manifest), manifest)
    files["PACKAGE.txt"] = MARKER.encode("ascii")
    return files


def diff_maps(expected, actual):
    errors = []
    for rel in sorted(expected):
        if rel not in actual:
            errors.append(f"missing akb/{rel}")
        elif actual[rel] != expected[rel]:
            errors.append(f"stale akb/{rel}")
    for rel in sorted(actual):
        if rel not in expected:
            errors.append(f"extra akb/{rel}")
    return errors


def self_test_diff():
    got = diff_maps({"a": b"1", "c": b"3"}, {"a": b"2", "b": b"9"})
    want = ["stale akb/a", "missing akb/c", "extra akb/b"]
    if got != want:
        return [f"package diff self-test failed: {got}"]
    return []


def actual_files():
    root = package_root()
    files = {}
    if not os.path.isdir(root):
        return files
    if os.path.islink(root):
        raise PackageError("akb must be a real directory, not a symlink")
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(dirnames)
        for name in dirnames:
            full = os.path.join(dirpath, name)
            if os.path.islink(full):
                rel = _rel(os.path.relpath(full, root))
                raise PackageError(f"akb/{rel} is a symlink")
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            rel = _rel(os.path.relpath(full, root))
            if os.path.islink(full):
                raise PackageError(f"akb/{rel} is a symlink")
            with open(full, "rb") as fh:
                files[rel] = fh.read()
    return files


def check_tree():
    errors = self_test_diff()
    if errors:
        return errors
    try:
        expected = expected_files()
        actual = actual_files()
    except PackageError as exc:
        return [str(exc)]
    if not actual:
        return ["akb/ is missing. Run tools/package_cursor_plugin.py"]
    return diff_maps(expected, actual)


def summary(files=None):
    files = files or expected_files()
    total = sum(len(data) for data in files.values())
    marker = len(files["PACKAGE.txt"])
    groups = {}
    for rel, data in files.items():
        top = rel.split("/", 1)[0]
        groups[top] = groups.get(top, 0) + len(data)
    return {
        "files": len(files),
        "bytes": total,
        "duplicated_bytes": total - marker,
        "marker_bytes": marker,
        "groups": groups,
    }


def _covers(expected, rel):
    if rel in expected:
        return True
    prefix = rel.rstrip("/") + "/"
    return any(key.startswith(prefix) for key in expected)


def write_tree():
    expected = expected_files()
    missing = [rel for rel in REQUIRED_PACKAGE_PATHS if not _covers(expected, rel)]
    if missing:
        raise PackageError("refusing to write akb/ without " + ", ".join(missing))
    root = package_root()
    os.makedirs(root, exist_ok=True)
    for rel, data in sorted(expected.items()):
        dest = os.path.join(root, *rel.split("/"))
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        if os.path.islink(dest):
            os.remove(dest)
        with open(dest, "wb") as fh:
            fh.write(data)
    for dirpath, dirnames, filenames in os.walk(root, topdown=False):
        for name in filenames:
            full = os.path.join(dirpath, name)
            rel = _rel(os.path.relpath(full, root))
            if rel not in expected or os.path.islink(full):
                os.remove(full)
        for name in dirnames:
            full = os.path.join(dirpath, name)
            if os.path.islink(full):
                os.remove(full)
            elif os.path.isdir(full) and not os.listdir(full):
                os.rmdir(full)
    return summary(expected)


def _powershell():
    candidates = [
        shutil.which("powershell.exe"),
        shutil.which("powershell"),
        "/mnt/c/Windows/System32/WindowsPowerShell/v1.0/powershell.exe",
        "C:\\Windows\\System32\\WindowsPowerShell\\v1.0\\powershell.exe",
    ]
    for candidate in candidates:
        if candidate and os.path.isfile(candidate):
            return candidate
    return None


def _windows_temp(powershell):
    result = subprocess.run(
        [powershell, "-NoProfile", "-Command", "[Console]::Out.Write($env:TEMP)"],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        check=False,
    )
    if result.returncode != 0:
        return None
    path = result.stdout.strip().rstrip("\\/")
    if re.match(r"^[A-Za-z]:\\", path):
        return path
    return None


def _to_wsl(path):
    if path.startswith("/"):
        return path
    match = re.match(r"^([A-Za-z]):[\\/](.*)$", path)
    if not match:
        raise PackageError(f"cannot translate path: {path}")
    rest = match.group(2).replace("\\", "/")
    if rest.startswith("/"):
        return "/mnt/" + match.group(1).lower() + rest
    return "/mnt/" + match.group(1).lower() + "/" + rest


def _outside_repo(path):
    repo = os.path.realpath(ROOT)
    got = os.path.realpath(path)
    return got != repo and not got.startswith(repo + os.sep)


def _copy_package(dest):
    src = package_root()
    if not os.path.isdir(src) or os.path.islink(src):
        raise PackageError("akb/ is not a real directory")
    os.makedirs(dest, exist_ok=True)
    for dirpath, dirnames, filenames in os.walk(src):
        dirnames[:] = sorted(dirnames)
        rel_dir = os.path.relpath(dirpath, src)
        target = dest if rel_dir == "." else os.path.join(dest, rel_dir)
        os.makedirs(target, exist_ok=True)
        for name in dirnames:
            if os.path.islink(os.path.join(dirpath, name)):
                raise PackageError("akb/ contains a symlink")
        for name in filenames:
            full = os.path.join(dirpath, name)
            if os.path.islink(full):
                raise PackageError(f"akb/ contains a symlink: {name}")
            shutil.copyfile(full, os.path.join(target, name))


def _value(output, key):
    prefix = key + "="
    for line in output.splitlines():
        if line.startswith(prefix):
            return line[len(prefix):]
    return None


def _same(left, right):
    return os.path.normcase(os.path.abspath(left)) == os.path.normcase(os.path.abspath(right))


def _run(cmd, env=None, cwd=None):
    return subprocess.run(
        cmd,
        cwd=cwd,
        env=env,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        check=False,
    )


def _direct_env(home=None):
    env = os.environ.copy()
    env.pop("PYTHONPATH", None)
    env.pop("MSYSTEM", None)
    env.pop("APOLLOCROSSDEV", None)
    if home:
        env["HOME"] = home
    return env


def _ps_quote(value):
    return "'" + value.replace("'", "''") + "'"


def _convert_fn():
    return (
        "function Convert-AkbPath([string]$p) {\n"
        "  if ($p.StartsWith('/')) { return $p }\n"
        "  if ($p -match '^[A-Za-z]:[\\\\/]') {\n"
        "    $drive = $p.Substring(0,1).ToLower()\n"
        "    $rest = $p.Substring(2) -replace '\\\\','/'\n"
        "    if ($rest.StartsWith('/')) { return \"/mnt/$drive$rest\" }\n"
        "    return \"/mnt/$drive/$rest\"\n"
        "  }\n"
        "  return $p\n"
        "}\n"
    )


def _run_powershell(powershell, body):
    return _run([powershell, "-NoProfile", "-Command", body])


def verify_installed_copy():
    """Copy only akb/ outside the repository and run the skill programs there.

    The disposable directory has the shape plugins/local/akb. It is not the
    user's live Cursor plugin folder. Returns a list of failures. Prints
    PASS lines for the behaviours that ran.
    """
    errors = []
    token = uuid.uuid4().hex[:8]
    powershell = _powershell()
    windows_temp = _windows_temp(powershell) if powershell else None
    home = tempfile.mkdtemp(prefix="akb-home-")
    base = None
    try:
        if windows_temp:
            win_base = windows_temp + "\\akb-cursor-disposable-" + token
            base = _to_wsl(win_base)
            if not _outside_repo(base):
                windows_temp = None
        if not windows_temp:
            base = tempfile.mkdtemp(prefix="akb-cursor-disposable-")
            win_base = None
        install = os.path.join(base, "plugins", "local", "akb")
        projects = os.path.join(base, "projects")
        os.makedirs(projects, exist_ok=True)
        _copy_package(install)
        for dirpath, dirnames, filenames in os.walk(install):
            for name in dirnames + filenames:
                if os.path.islink(os.path.join(dirpath, name)):
                    errors.append("disposable install contains a symlink")
        if not _outside_repo(install):
            errors.append("disposable install is inside the repository checkout")
            return errors
        print(f"INSTALL disposable={install}")
        print("NOTE=this is not the live ~/.cursor/plugins/local directory")
        errors.extend(_discover(install))
        errors.extend(_resolve_cases(install, projects))
        errors.extend(_scaffold_cases(install, projects))
        errors.extend(_find_acd(install, projects, home))
        errors.extend(_lesson_gate(install, projects))
        errors.extend(_lesson_checkers(install))
        if powershell and win_base:
            errors.extend(_powershell_cases(powershell, win_base, install, projects, token))
        elif not powershell:
            print("RESULT powershell-to-wsl NOT VERIFIED")
            print("REASON=powershell.exe is not available, so the Windows host launch was not run")
        else:
            print("RESULT powershell-to-wsl NOT VERIFIED")
            print("REASON=the disposable install is not on a Windows drive, so path translation was not run")
    except PackageError as exc:
        errors.append(str(exc))
    finally:
        shutil.rmtree(home, ignore_errors=True)
        if base:
            shutil.rmtree(base, ignore_errors=True)
    return errors


def _discover(install):
    errors = []
    for name in SKILL_NAMES:
        path = os.path.join(install, "skills", name, "SKILL.md")
        text = open(path, encoding="utf-8").read()
        match = re.search(r"(?m)^name:\s*(\S+)\s*$", text)
        if not match or match.group(1) != name:
            errors.append(f"installed skill {name} is missing its frontmatter name")
        if not re.search(r"(?m)^description:\s*\S", text):
            errors.append(f"installed skill {name} has no description")
    rule = open(os.path.join(install, "rules", "apollo-v4.mdc"), encoding="utf-8").read()
    if "alwaysApply: false" not in rule or re.search(r"(?m)^globs:", rule):
        errors.append("installed rule apollo-v4.mdc is not the agent-requestable rule")
    if "description:" not in rule:
        errors.append("installed rule apollo-v4.mdc has no description")
    manifest = json.loads(open(os.path.join(install, ".cursor-plugin", "plugin.json"), encoding="utf-8").read())
    if manifest.get("name") != "akb":
        errors.append("installed plugin.json name is not akb")
    if os.path.exists(os.path.join(install, ".cursor-plugin", "marketplace.json")):
        errors.append("installed package must not contain a nested marketplace.json")
    for dirpath, _, filenames in os.walk(install):
        for name in filenames:
            if name.endswith(".sh"):
                data = open(os.path.join(dirpath, name), "rb").read()
                if b"\r" in data:
                    errors.append(f"installed script has CR: {name}")
    if not errors:
        print("INSTALL discovers apollo-new-project, apollo-build, akb-lesson, and apollo-v4: PASS")
    return errors


def _resolve_py(install):
    return [sys.executable, os.path.join(install, "tools", "resolve_kb.py")]


def _resolve_cases(install, projects):
    errors = []
    bare = os.path.join(projects, "nosub")
    os.makedirs(bare)
    env = _direct_env()
    result = _run(_resolve_py(install) + [bare], env=env, cwd=bare)
    root = _value(result.stdout, "KB_ROOT")
    if result.returncode != 0 or _value(result.stdout, "KB_SOURCE") != "plugin" or not root or not _same(root, install):
        errors.append(f"installed resolver did not use the package when no submodule exists:\n{result.stdout}")
    elif _same(root, ROOT):
        errors.append("installed resolver returned the repository checkout")
    pinned = os.path.join(projects, "pinned")
    sub = os.path.join(pinned, "ApolloKnowledgeBase")
    os.makedirs(os.path.join(sub, "skills"))
    with open(os.path.join(sub, "AGENTS.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# AGENTS.md: pinned\n")
    result = _run(_resolve_py(install) + [pinned], env=env, cwd=pinned)
    root = _value(result.stdout, "KB_ROOT")
    if result.returncode != 0 or _value(result.stdout, "KB_SOURCE") != "submodule" or not root or not _same(root, sub):
        errors.append(f"installed resolver did not prefer the initialized submodule:\n{result.stdout}")
    broken = os.path.join(projects, "uninit")
    os.makedirs(os.path.join(broken, "ApolloKnowledgeBase"))
    with open(os.path.join(broken, ".gitmodules"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write('[submodule "ApolloKnowledgeBase"]\n\tpath = ApolloKnowledgeBase\n')
    result = _run(_resolve_py(install) + [broken], env=env, cwd=broken)
    if result.returncode == 0 or "PROBLEM=" not in result.stdout or "RECOVERY=" not in result.stdout:
        errors.append(f"installed resolver accepted an uninitialized submodule:\n{result.stdout}")
    if _value(result.stdout, "KB_SOURCE") == "plugin":
        errors.append("installed resolver fell back to the package for an uninitialized submodule")
    if not errors:
        print("INSTALL knowledge resolution, submodule precedence, and uninitialized refusal: PASS")
    return errors


def _script(install, rel):
    return os.path.join(install, *rel.split("/"))


def _scaffold_cases(install, projects):
    errors = []
    shell = shutil.which("sh")
    if not shell:
        print("RESULT installed-scaffold NOT VERIFIED")
        print("REASON=sh is not on PATH, so write-project-files.sh was not executed")
        return errors
    basic = os.path.join(projects, "basicprobe")
    os.makedirs(basic)
    script = _script(install, "skills/apollo-new-project/scripts/write-project-files.sh")
    result = _run([shell, script, "--project", basic, "--setup", "basic", "--no-claude"], env=_direct_env(), cwd=basic)
    agents = os.path.join(basic, "AGENTS.md")
    rule = os.path.join(basic, ".cursor", "rules", "apollo-v4.mdc")
    if result.returncode != 0 or not os.path.isfile(agents) or not os.path.isfile(rule):
        errors.append(f"installed basic scaffold failed:\n{result.stdout}")
    else:
        text = open(agents, encoding="utf-8").read()
        root = _value(result.stdout, "KB_ROOT")
        if "not set yet" not in text or os.path.exists(os.path.join(basic, "main.c")):
            errors.append("installed basic scaffold did not write the unset project files")
        if not root or not _same(root, install):
            errors.append(f"basic scaffold did not read the installed package:\n{result.stdout}")
    marked = os.path.join(projects, "marked")
    sub = os.path.join(marked, "ApolloKnowledgeBase")
    os.makedirs(os.path.join(sub, "skills"))
    os.makedirs(os.path.join(sub, "templates", "repo"))
    with open(os.path.join(sub, "AGENTS.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# AGENTS.md: pinned\n")
    template = open(os.path.join(install, "templates", "repo", "AGENTS.md"), encoding="utf-8").read()
    with open(os.path.join(sub, "templates", "repo", "AGENTS.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(template + "\nSUBMODULE_TEMPLATE_MARKER\n")
    shutil.copyfile(
        os.path.join(install, "templates", "repo", "CLAUDE.md"),
        os.path.join(sub, "templates", "repo", "CLAUDE.md"),
    )
    result = _run([shell, script, "--project", marked, "--setup", "basic"], env=_direct_env(), cwd=marked)
    if result.returncode != 0 or "KB_SOURCE=submodule" not in result.stdout:
        errors.append(f"installed scaffold did not prefer the submodule:\n{result.stdout}")
    elif "SUBMODULE_TEMPLATE_MARKER" not in open(os.path.join(marked, "AGENTS.md"), encoding="utf-8").read():
        errors.append("installed scaffold did not read the submodule template")
    refused = os.path.join(projects, "refused")
    os.makedirs(os.path.join(refused, "ApolloKnowledgeBase"))
    with open(os.path.join(refused, ".gitmodules"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write('[submodule "ApolloKnowledgeBase"]\n\tpath = ApolloKnowledgeBase\n')
    result = _run(
        [shell, script, "--project", refused, "--setup", "basic", "--no-claude"],
        env=_direct_env(),
        cwd=refused,
    )
    if result.returncode == 0 or "PROBLEM=" not in result.stdout or os.path.exists(os.path.join(refused, "AGENTS.md")):
        errors.append(f"installed scaffold wrote a project against an uninitialized submodule:\n{result.stdout}")
    if not errors:
        print("INSTALL basic project creation and submodule scaffold precedence: PASS")
    return errors


def _find_acd(install, projects, home):
    errors = []
    shell = shutil.which("sh")
    if not shell:
        print("RESULT installed-find-acd NOT VERIFIED")
        print("REASON=sh is not on PATH, so find-acd.sh was not executed")
        return errors
    project = os.path.join(projects, "findprobe")
    os.makedirs(project)
    script = _script(install, "skills/apollo-build/scripts/find-acd.sh")
    result = _run([shell, script, "--offline", project], env=_direct_env(home), cwd=project)
    if result.returncode == 0 or "ApolloCrossDev not found" not in result.stdout:
        errors.append(f"installed find-acd.sh did not report a missing toolchain:\n{result.stdout}")
    elif "make " in " ".join(result.args):
        errors.append("find-acd invocation included make")
    else:
        print("INSTALL ApolloCrossDev discovery without upload: PASS")
    return errors


def _lesson_gate(install, projects):
    errors = []
    shell = shutil.which("sh")
    if not shell:
        print("RESULT installed-submit-gate NOT VERIFIED")
        print("REASON=sh is not on PATH, so submit-gate.sh was not executed")
        return errors
    folder = os.path.join(projects, "lesson")
    os.makedirs(folder)
    draft = os.path.join(folder, "draft.md")
    approved = os.path.join(folder, "approved.md")
    with open(draft, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("draft\n")
    with open(approved, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("draft\n")
    script = _script(install, "skills/akb-lesson/scripts/submit-gate.sh")
    good = _run(
        [shell, script, "--draft", draft, "--approved", approved, "--destination", "ExampleOwner/ExampleRepo"],
        env=_direct_env(),
        cwd=folder,
    )
    with open(approved, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("edited\n")
    bad = _run(
        [shell, script, "--draft", draft, "--approved", approved, "--destination", "ExampleOwner/ExampleRepo"],
        env=_direct_env(),
        cwd=folder,
    )
    empty = _run(
        [shell, script, "--draft", draft, "--approved", draft, "--destination", ""],
        env=_direct_env(),
        cwd=folder,
    )
    if good.returncode != 0 or "SUBMIT=yes" not in good.stdout:
        errors.append(f"installed submit gate rejected a matching draft:\n{good.stdout}")
    if bad.returncode == 0 or "SUBMIT=no" not in bad.stdout:
        errors.append("installed submit gate allowed a changed draft")
    if empty.returncode == 0 or "SUBMIT=no" not in empty.stdout:
        errors.append("installed submit gate allowed an empty destination")
    if not errors:
        print("INSTALL lesson submission gate: PASS")
    return errors


